// Helper to generate realistic candle history
export function generateCandles(basePrice: number, count: number = 60, volatility: number = 0.015, trend: number = 0.0005) {
  const candles = [];
  let current = basePrice * 0.92;
  const now = Date.now();
  const stepMs = 3600 * 1000; // 1 hour steps

  for (let i = 0; i < count; i++) {
    const timestamp = now - (count - i) * stepMs;
    const date = new Date(timestamp);
    const timeStr = `${date.getMonth() + 1}/${date.getDate()} ${date.getHours()}:00`;
    
    const change = (Math.random() - 0.48 + trend) * volatility * current;
    const open = current;
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.random() * volatility * 0.6 * current;
    const low = Math.min(open, close) - Math.random() * volatility * 0.6 * current;
    const volume = Math.round((Math.random() * 0.8 + 0.4) * 150000);

    candles.push({
      time: timeStr,
      timestamp,
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      close: parseFloat(close.toFixed(2)),
      volume,
    });
    current = close;
  }
  return candles;
}

// Helper to extract sparkline
function extractSparkline(candles: ReturnType<typeof generateCandles>, points = 24): number[] {
  const step = Math.max(1, Math.floor(candles.length / points));
  const res: number[] = [];
  for (let i = 0; i < candles.length; i += step) {
    res.push(candles[i].close);
  }
  return res;
}

